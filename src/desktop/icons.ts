/** Name of a desktop icon. */
export type IconName = keyof typeof ICONS;

/** The lit pixels of an icon as horizontal runs, to draw them as rectangles. */
export function iconRuns(rows: readonly string[]): IconRun[] {
  const runs: IconRun[] = [];
  rows.forEach((row, y) => {
    let start = -1;
    for (let x = 0; x <= row.length; x++) {
      const lit = row[x] === "#";
      if (lit && start < 0) {
        start = x;
      } else if (!lit && start >= 0) {
        runs.push({ x: start, y, width: x - start });
        start = -1;
      }
    }
  });
  return runs;
}
